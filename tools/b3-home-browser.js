'use strict';
const assert=require('node:assert/strict');
module.exports=async function home(page){
  await page.evaluate(()=>{S.babyOn=true;NTUI.go('home');});
  const root=page.locator('#b3Root');
  assert.equal(await root.getByRole('heading',{name:'Gerade wichtig'}).count(),1);
  assert.equal(await root.getByText('Deine Bereiche',{exact:true}).count(),0);
  const planHint=root.locator('[data-priority-id^="plan-"]');
  if(await planHint.count()){
    assert.equal(await planHint.getByRole('button',{name:'Heute ausblenden'}).isVisible(),false,'secondary hint options stay compact initially');
    await planHint.locator('summary').click();await planHint.getByRole('button',{name:'Heute ausblenden'}).click();
    assert.equal(await planHint.count(),0,'expanded explanation retains the real dismissal action');
  }
  assert.match(await root.locator('.b3-next-side').textContent(),/Links/);
  assert.deepEqual(await page.evaluate(()=>S.ui.homeActions),['wickeln','foto','stillen'],'legacy launch bar imported in original order');
  await root.getByRole('button',{name:'Rechts starten',exact:true}).click();
  const first=await page.evaluate(()=>NTBaby.runningFeed());assert.equal(first.side,'r');
  await page.reload({waitUntil:'load'});await page.waitForFunction(()=>NTUI.enabled());
  assert.equal(await page.evaluate(()=>NTBaby.runningFeed().id),first.id,'running timer survives reopening');
  await page.evaluate(()=>NTBaby.toggleSleep());
  assert.equal(await root.locator('.b3-active').count(),1,'simultaneous activity stays in one priority card');
  const wake=root.locator('.b3-active').getByRole('button',{name:'Wach jetzt'});
  assert.equal(await wake.isVisible(),true,'sleep stays actionable beside active feeding');
  await wake.click();
  assert.equal(await page.evaluate(()=>NTBaby.runningFeed().id),first.id,'ending sleep leaves the feeding timer running');
  await root.locator('.b3-active [data-act="NTBaby.switchFeed"]').click();
  const second=await page.evaluate(()=>NTBaby.runningFeed());assert.equal(second.side,'l');assert.notEqual(second.id,first.id);
  await page.evaluate(id=>NTBaby.stopFeed(true,id),first.id);
  assert.equal(await page.evaluate(()=>NTBaby.runningFeed().id),second.id,'stale remote stop cannot affect new timer');
  await root.locator('.b3-active [data-act="NTBaby.stopFeed"]').click();
  assert.equal(await page.evaluate(()=>NTBaby.runningFeed()),null);
  await page.evaluate(()=>NTUI.go('baby'));
  assert.match(await page.locator('#b3BabyStatus .b3-next-side').textContent(),/Rechts/);
  assert.equal(await page.locator('#babyOvQuickBtns button').count(),10,'all ten personal quick buttons remain');
  await page.evaluate(()=>NTUI.go('home'));
  await root.getByRole('button',{name:'Anpassen',exact:true}).click();
  await page.evaluate(()=>{
    ['wickeln','foto','stillen'].forEach(id=>NTUIHome.toggle(id));
    ['stillen','wickeln','schlaf','mahlzeit','einkauf','plan'].forEach(id=>NTUIHome.toggle(id));
    NTUIHome.toggle('wasser');NTUIHome.move('schlaf',-1);
  });
  assert.equal(await page.evaluate(()=>S.ui.homeActions.length),6,'seventh action rejected');
  assert.deepEqual(await page.evaluate(()=>S.launchBar),['wickeln','foto','stillen']);
  assert.equal(await page.evaluate(()=>S.babyQuick.length),10);
  await page.evaluate(()=>closeOv('b3HomePrefsOv'));
  assert.equal(await page.evaluate(()=>document.activeElement.id),'b3Title','closing after a home rerender restores a visible focus target');
  assert.equal(await root.locator('.b3-quick button').count(),6);
  await page.evaluate(()=>{S.babyOn=false;NTUI.refresh();});
  const unavailable=root.getByRole('button',{name:'Stillen · Funktion einschalten'});
  assert.equal(await unavailable.isVisible(),true,'existing quick actions keep their places when a module is disabled');
  await unavailable.click();await page.locator('#featSheetOv.open').waitFor();
  await page.evaluate(()=>{closeOv('featSheetOv');S.babyOn=true;saveS();NTUI.refresh();});
  await page.reload({waitUntil:'load'});await page.waitForFunction(()=>NTUI.enabled());
  assert.deepEqual(await page.evaluate(()=>S.ui.homeActions),['stillen','schlaf','wickeln','mahlzeit','einkauf','plan']);
  await page.evaluate(()=>{S.babyLog={};saveS();NTUI.refresh();});
  assert.match(await root.locator('.b3-next-side').textContent(),/Noch kein Vorschlag/);
  await page.evaluate(()=>NTUIHome.run('stillen'));
  assert.equal(await page.locator('#b3ActionBody button').count(),2,'no fabricated side without history');
  assert.equal(await page.evaluate(()=>NTBaby.runningFeed()),null,'choosing a side does not start a timer');
  await page.evaluate(()=>closeOv('b3ActionOv'));
  console.log('B3 home: breast sequence, running ID, reopen, side switch, six configurable actions and ten Baby buttons OK');
};
