'use strict';
const assert=require('node:assert/strict'),path=require('node:path');
const {fixture}=require('./fixtures/b3-state');
module.exports=async function shell(browser,width,output,base){
  const ctx=await browser.newContext({viewport:{width,height:844},isMobile:true,hasTouch:true,timezoneId:'Europe/Berlin'});
  try{
    await ctx.route('**/*',r=>/^https?:\/\/(127\.0\.0\.1|localhost)(:|\/)/.test(r.request().url())?r.continue():r.abort());
    const page=await ctx.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));
    const data=fixture(new Date().toLocaleDateString('sv-SE',{timeZone:'Europe/Berlin'}));
    await page.addInitScript(data=>{
      if(localStorage.getItem('nt_v6'))return;
      localStorage.setItem('nt_v6',JSON.stringify(data.state));localStorage.setItem('nt_x',JSON.stringify({fc:data.foodCache,cf:data.customFoods,rc:data.recipes}));localStorage.setItem('nt_gate_skipped','1');
    },data);
    await page.goto(base+'?ui=b3',{waitUntil:'load'});
    await page.waitForFunction(()=>window.NTUI&&NTUI.enabled());
    const nav=page.getByRole('navigation',{name:'Hauptnavigation'});
    assert.equal(await nav.locator('button').count(),5);
    await nav.getByRole('button',{name:'Ernährung',exact:true}).click();
    await nav.getByRole('button',{name:'Erfassen: Ernährung'}).click();
    await page.locator('#pickerOv.open').waitFor();
    assert.equal(await page.locator('#pickerOv .picker-tab').count(),7);
    await page.evaluate(()=>closeOv('pickerOv'));
    await nav.getByRole('button',{name:'Baby-Tagebuch',exact:true}).click();
    await nav.getByRole('button',{name:'Erfassen: Baby-Tagebuch'}).click();
    assert.equal(await page.locator('#b3ActionBody button').count(),11);
    await page.locator('#b3ActionBody button').filter({hasText:'Flasche'}).click();
    await page.locator('#babyEntryOv.open').waitFor();
    await page.evaluate(()=>closeOv('babyEntryOv'));
    await page.evaluate(()=>NTUI.go('household'));
    await nav.getByRole('button',{name:'Erfassen: Haushalt'}).click();
    await page.locator('#b3ActionBody button').filter({hasText:'Vorratsartikel'}).click();
    await page.locator('#pantryItemOv.open').waitFor();await page.evaluate(()=>closeOv('pantryItemOv'));
    await page.evaluate(()=>NTUI.go('shop'));await nav.getByRole('button',{name:'Erfassen: Einkaufszettel'}).click();
    await page.locator('#shopAddOv.open').waitFor();await page.evaluate(()=>closeOv('shopAddOv'));
    await page.evaluate(()=>NTUI.go('plan'));await nav.getByRole('button',{name:'Erfassen: Wochenplan'}).click();
    await page.locator('#b3ActionBody button').filter({hasText:'Mittagessen'}).click();
    await page.locator('#planPickOv.open').waitFor();await page.evaluate(()=>closeOv('planPickOv'));
    await page.evaluate(()=>NTUI.go('book'));await nav.getByRole('button',{name:'Erfassen: Kochbuch'}).click();
    await page.locator('#recNewOv.open').waitFor();await page.evaluate(()=>closeOv('recNewOv'));
    await page.evaluate(()=>NTUI.go('more'));
    await page.locator('#b3CatalogQuery').fill('Backup');
    assert.ok(await page.locator('#b3Catalog button').count()>0);
    await page.getByRole('button',{name:'Navigation anpassen',exact:true}).click();
    await page.locator('#b3Slot0').selectOption('shop');await page.locator('#b3Slot1').selectOption('shop');
    await page.locator('#b3PrefsOv [data-act="NTUI.savePreferences"]').click();
    assert.equal(await page.locator('#b3PrefsOv').evaluate(el=>el.classList.contains('open')),true,'duplicate target rejected');
    await page.locator('#b3Slot1').selectOption('pantry');await page.locator('#b3Slot2').selectOption('more');
    await page.locator('#b3PrefsOv [data-act="NTUI.savePreferences"]').click();
    await page.evaluate(()=>NTUI.go('home'));
    await page.screenshot({path:path.join(output,'b3-shell-'+width+'.png'),fullPage:true});
    await page.reload({waitUntil:'load'});await page.waitForFunction(()=>NTUI.enabled());
    assert.deepEqual(await page.evaluate(()=>S.ui.navSlots),['shop','pantry','more']);
    for(const key of ['babyQuick','launchBar','dashOrder','dashHidden','shopList','pantry','mealPlan','links'])assert.deepEqual(await page.evaluate(key=>S[key],key),data.state[key],key+' preserved');
    await page.evaluate(()=>NTUI.go('nutrition'));
    await page.evaluate(()=>NTUI.go('more'));await page.goBack();
    await page.waitForFunction(()=>NTUI.context()==='nutrition');
    await page.evaluate(()=>{S.babyOn=false;NTUI.go('baby');});
    assert.equal(await page.evaluate(()=>NTUI.context()),'more','disabled feature goes to More');
    // Use the actual service worker and caches, not a synthetic fetch fallback.
    await page.evaluate(async()=>{await navigator.serviceWorker.register(new URL('sw.js',location.href).href,{scope:'./'});await navigator.serviceWorker.ready;});
    await page.reload({waitUntil:'load'});await page.waitForFunction(()=>!!navigator.serviceWorker.controller&&NTUI.enabled());
    await page.waitForFunction(async()=>!!(await caches.match(location.href)));
    await ctx.setOffline(true);await page.reload({waitUntil:'load'});
    await page.waitForFunction(()=>NTUI.enabled());
    assert.deepEqual(await page.evaluate(()=>S.ui.navSlots),['shop','pantry','more'],'offline reload retains navigation');
    await page.evaluate(()=>NTUI.go('nutrition'));await nav.getByRole('button',{name:'Erfassen: Ernährung'}).click();
    await page.locator('#pickerOv.open').waitFor();await page.evaluate(()=>closeOv('pickerOv'));
    await ctx.setOffline(false);
    if(require('node:fs').existsSync(path.resolve(__dirname,'../js/ui-home.js')))await require('./b3-home-browser')(page);
    await page.goto(base+'?ui=classic',{waitUntil:'load'});
    assert.equal(await page.evaluate(()=>NTUI.enabled()),false,'emergency route bypasses new shell');
    assert.equal(await page.locator('#mainScreen').evaluate(el=>el.classList.contains('active')),true);
    assert.deepEqual(errors,[]);
    console.log('B3 shell '+width+'px: context +, eleven types, preferences, Back, feature off, classic recovery OK');
  }finally{await ctx.close();}
};
